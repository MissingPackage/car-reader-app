def esc(t):
    t = t.replace("&","&amp;").replace("<","&lt;").replace("'", "\\'").replace('"','\\"')
    if t.startswith("@") or t.startswith("?"): t = "\\"+t
    return t

def write(path, idx, lang):
    out = ['<?xml version="1.0" encoding="utf-8"?>', '<resources>']
    for k,en,it in S:
        v = (en,it)[idx]
        attr = ' translatable="false"' if (k=="app_name" and idx==0) else ''
        if k=="app_name" and idx==1: continue
        out.append(f'    <string name="{k}"{attr}>{esc(v)}</string>')
    for k,forms in PLURALS:
        out.append(f'    <plurals name="{k}">')
        for q,(en,it) in forms.items():
            out.append(f'        <item quantity="{q}">{esc((en,it)[idx])}</item>')
        if idx==1:
            for q,v in IT_EXTRA.get(k,{}).items():
                out.append(f'        <item quantity="{q}">{esc(v)}</item>')
        out.append('    </plurals>')
    out.append('</resources>')
    open(path,'w').write("\n".join(out)+"\n")


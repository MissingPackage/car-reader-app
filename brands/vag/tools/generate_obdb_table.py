#!/usr/bin/env python3
"""Generate a bundled Kotlin signal table from an OBDb signal set (signalsets/v3/default.json).

Usage:
  curl -sL https://raw.githubusercontent.com/OBDb/<repo>/main/signalsets/v3/default.json -o <repo>.json
  python3 -I generate_obdb_table.py <repo>.json <repo> <commit-sha> <KotlinObjectName> <out.kt>

Kept: Mode 0x22 commands on 11-bit CAN headers (3 hex digits). Dropped: commands flagged "dbg"
(still under investigation in OBDb) and 29-bit headers (the VAG module scans 11-bit CAN only).
The output is licensed CC BY-SA 4.0 like its source.
"""
import datetime
import json
import sys

FIELDS = "hdr|did|din|fyFrom|fyTo|fyYears|id|path|name|bix|len|sign|blsb|mul|div|add|min|max|nullmin|nullmax|unit|map"
CHUNK = 30000


def clean(text):
    text = str(text).replace("​", "").strip()
    for bad in ("|", "\n", '"""', "$"):
        if bad in text:
            raise SystemExit(f"Unsupported character {bad!r} in {text!r}")
    return text


def num(v):
    if v is None:
        return ""
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, float) and v.is_integer():
        return str(int(v))
    return str(v)


def main():
    src, repo, sha, obj, out = sys.argv[1:6]
    data = json.load(open(src))
    lines, dropped_dbg, dropped_29 = [], 0, 0
    for c in data["commands"]:
        if "22" not in c["cmd"]:
            continue
        if c.get("dbg"):
            dropped_dbg += len(c["signals"])
            continue
        if len(c["hdr"]) != 3:
            dropped_29 += len(c["signals"])
            continue
        f = c.get("filter") or {}
        for s in c["signals"]:
            fmt = s["fmt"]
            mp = fmt.get("map")
            map_text = ""
            if mp:
                parts = []
                for k, v in mp.items():
                    label = v.get("description", v.get("value")) if isinstance(v, dict) else v
                    label = clean(label)
                    if ";" in label or "=" in label:
                        raise SystemExit(f"Unsupported map label {label!r}")
                    parts.append(f"{int(k)}={label}")
                map_text = ";".join(parts)
            row = [
                c["hdr"].upper(), c["cmd"]["22"].upper(), c.get("din", ""),
                num(f.get("from")), num(f.get("to")), ",".join(str(y) for y in f.get("years", [])),
                clean(s["id"]), clean(s.get("path", "")), clean(s["name"]),
                num(fmt.get("bix", 0)), num(fmt["len"]), num(bool(fmt.get("sign", False))), num(bool(fmt.get("blsb", False))),
                num(fmt.get("mul")), num(fmt.get("div")), num(fmt.get("add")),
                num(fmt.get("min")), num(fmt.get("max")), num(fmt.get("nullmin")), num(fmt.get("nullmax")),
                clean(fmt.get("unit", "scalar")), map_text,
            ]
            lines.append("|".join(row))

    chunks, cur = [], []
    size = 0
    for line in lines:
        if size + len(line) + 1 > CHUNK and cur:
            chunks.append(cur)
            cur, size = [], 0
        cur.append(line)
        size += len(line) + 1
    if cur:
        chunks.append(cur)

    today = datetime.date.today().isoformat()
    url = f"https://github.com/OBDb/{repo}/blob/{sha}/signalsets/v3/default.json"
    with open(out, "w") as fh:
        fh.write(f"""// GENERATED by brands/vag/tools/generate_obdb_table.py on {today}. Do not edit by hand.
// Source: {url}
//         (raw: https://raw.githubusercontent.com/OBDb/{repo}/main/signalsets/v3/default.json)
// Licensed CC BY-SA 4.0, derived from OBDb (https://github.com/OBDb). See brands/vag/ATTRIBUTION.md.
// Changes from the source: Mode 22 signals on 11-bit CAN only; {dropped_dbg} signals flagged "dbg" and
// {dropped_29} signals on 29-bit headers left out; fields flattened to one line per signal.
// Columns: {FIELDS}
package io.carreader.brands.vag.data

internal object {obj} {{
    const val SOURCE = "OBDb {repo}"
    const val URL = "{url}"
    const val SIGNAL_COUNT = {len(lines)}

    val chunks: Array<String> get() = arrayOf({", ".join(f"C{i}" for i in range(len(chunks)))})
""")
        for i, ch in enumerate(chunks):
            fh.write(f'\n    private const val C{i} = """\n' + "\n".join(ch) + '\n"""\n')
        fh.write("}\n")
    print(f"{repo}: {len(lines)} signals kept, {dropped_dbg} dbg dropped, {dropped_29} 29-bit dropped, {len(chunks)} chunks")


if __name__ == "__main__":
    main()

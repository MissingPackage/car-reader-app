#!/usr/bin/env python3
"""Generate a bundled Kotlin signal table (format 2) from an OBDb signal set (signalsets/v3/default.json).

Usage:
  curl -sL https://raw.githubusercontent.com/OBDb/<repo>/<sha>/signalsets/v3/default.json -o <repo>.json
  python3 -I generate_obdb_table.py <repo>.json <repo> <commit-sha> <KotlinObjectName> <kotlin.package> \\
      <attribution file, repo-relative> <out.kt>

Kept: Mode 0x22 commands on 11-bit (3 hex digits) and 29-bit (4 hex digits "DAxx", meaning 18DAxxF1) headers,
read in the default or the extended (0x03) session. Dropped: commands flagged "dbg" (still under
investigation in OBDb) and commands that need another diagnostic session (e.g. PSA 0xC0), which the app's
read-only gate does not open. OBDb "dbgfilter" (years a row is not verified for) and "fcm1" are not
applied: the app does not know the model year, and its driver chooses flow control itself. The response id ("rax") is written in full: 11-bit as is, 29-bit "xx" as 18DAF1xx.
Parsed by io.carreader.core.brand.obdb.ObdbSignalTable. The output is licensed CC BY-SA 4.0 like its source.
"""
import datetime
import json
import sys

FIELDS = "hdr|rax|did|din|fyFrom|fyTo|fyYears|id|path|name|bix|len|sign|blsb|mul|div|add|min|max|nullmin|nullmax|unit|map"
CHUNK = 30000
SESSIONS = {"", "03"}


def clean(text):
    text = str(text).replace("​", "").strip()
    for bad in ("|", "\n", '"""', "$"):
        if bad in text:
            raise SystemExit(f"Unsupported character {bad!r} in {text!r}")
    return text


def num(v):
    if v is None:
        return ""
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, float) and v.is_integer():
        return str(int(v))
    return str(v)


def addresses(cmd):
    hdr = cmd["hdr"].upper()
    rax = (cmd.get("rax") or "").upper()
    if len(hdr) == 3:
        return hdr, rax
    if len(hdr) == 4 and hdr.startswith("DA"):
        target = hdr[2:]
        return f"18DA{target}F1", (f"18DAF1{rax}" if rax else f"18DAF1{target}")
    return None, None


def main():
    src, repo, sha, obj, package, attribution, out = sys.argv[1:8]
    data = json.load(open(src))
    lines, dropped_dbg, dropped_session, dropped_hdr = [], 0, 0, 0
    for c in data["commands"]:
        if "22" not in c["cmd"]:
            continue
        if c.get("dbg"):
            dropped_dbg += len(c["signals"])
            continue
        din = c.get("din", "").upper()
        if din not in SESSIONS:
            dropped_session += len(c["signals"])
            continue
        hdr, rax = addresses(c)
        if hdr is None:
            dropped_hdr += len(c["signals"])
            continue
        f = c.get("filter") or {}
        for s in c["signals"]:
            fmt = s["fmt"]
            mp = fmt.get("map")
            map_text = ""
            if mp:
                parts = []
                for k, v in mp.items():
                    label = v.get("description", v.get("value")) if isinstance(v, dict) else v
                    label = clean(label)
                    if ";" in label or "=" in label:
                        raise SystemExit(f"Unsupported map label {label!r}")
                    parts.append(f"{int(k)}={label}")
                map_text = ";".join(parts)
            row = [
                hdr, rax, c["cmd"]["22"].upper(), din,
                num(f.get("from")), num(f.get("to")), ",".join(str(y) for y in f.get("years", [])),
                clean(s["id"]), clean(s.get("path", "")), clean(s["name"]),
                num(fmt.get("bix", 0)), num(fmt["len"]), num(bool(fmt.get("sign", False))), num(bool(fmt.get("blsb", False))),
                num(fmt.get("mul")), num(fmt.get("div")), num(fmt.get("add")),
                num(fmt.get("min")), num(fmt.get("max")), num(fmt.get("nullmin")), num(fmt.get("nullmax")),
                clean(fmt.get("unit", "scalar")), map_text,
            ]
            lines.append("|".join(row))

    chunks, cur = [], []
    size = 0
    for line in lines:
        if size + len(line) + 1 > CHUNK and cur:
            chunks.append(cur)
            cur, size = [], 0
        cur.append(line)
        size += len(line) + 1
    if cur:
        chunks.append(cur)

    today = datetime.date.today().isoformat()
    url = f"https://github.com/OBDb/{repo}/blob/{sha}/signalsets/v3/default.json"
    with open(out, "w") as fh:
        fh.write(f"""// GENERATED by tools/obdb/generate_obdb_table.py on {today}. Do not edit by hand.
// Source: {url}
// Licensed CC BY-SA 4.0, derived from OBDb (https://github.com/OBDb). See {attribution}.
// Changes from the source: Mode 22 signals only; {dropped_dbg} signals flagged "dbg", {dropped_session} signals
// needing a non-default, non-extended session and {dropped_hdr} on unsupported headers left out; fields
// flattened to one line per signal, 29-bit ids written in full.
// Columns: {FIELDS}
package {package}

import io.carreader.core.brand.obdb.ObdbTable

internal object {obj} : ObdbTable {{
    override val source = "OBDb {repo}"
    override val url = "{url}"
    const val SIGNAL_COUNT = {len(lines)}

    override val chunks: Array<String> get() = arrayOf({", ".join(f"C{i}" for i in range(len(chunks)))})
""")
        for i, ch in enumerate(chunks):
            fh.write(f'\n    private const val C{i} = """\n' + "\n".join(ch) + '\n"""\n')
        fh.write("}\n")
    print(f"{repo}: {len(lines)} signals kept, {dropped_dbg} dbg, {dropped_session} other session, {dropped_hdr} other headers dropped, {len(chunks)} chunks")


if __name__ == "__main__":
    main()
